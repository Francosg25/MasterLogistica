"""Exercise generated deployment configuration and release tamper detection."""

import hashlib
import importlib.util
import json
import os
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    result = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(result)
    return result


configure = module("server_config", ROOT / "deploy/linux/configure.py")
release = module("release_verify", ROOT / "deploy/linux/release.py")


class DeploymentTests(unittest.TestCase):
    def setUp(self):
        self.folder = tempfile.TemporaryDirectory(prefix="native deployment ")
        self.addCleanup(self.folder.cleanup)
        self.root = Path(self.folder.name)

    def test_rendered_config_keeps_https_origins_and_proxy_in_agreement(self):
        configure.render("Logistica.Example.TEST", self.root)
        api = (self.root / "api.env").read_text()
        nginx = (self.root / "masterlogistica.conf").read_text()
        self.assertIn('ALLOWED_ORIGINS=["https://logistica.example.test"]', api)
        self.assertIn('TRUSTED_PROXY_IPS=["127.0.0.1"]', api)
        self.assertIn("proxy_set_header X-Forwarded-Proto https;", nginx)
        self.assertIn("proxy_set_header Host logistica.example.test;", nginx)
        self.assertNotIn("MIGRATION_DATABASE_URL", api)
        self.assertNotIn("@DOMAIN@", nginx)
        if os.name != "nt":
            self.assertEqual((self.root / "api.env").stat().st_mode & 0o777, 0o600)
        with self.assertRaises(ValueError):
            configure.render("other.example.test", self.root)

    def test_domain_cannot_inject_proxy_directives_or_shell_text(self):
        for value in (
            "https://host.test",
            "host.test;include /etc/passwd",
            "host.test\nX",
            "*.example.test",
            "a/b.test",
        ):
            with self.subTest(value=value), self.assertRaises(ValueError):
                configure.render(value, self.root)
        self.assertEqual(list(self.root.iterdir()), [])

    def prepared(self):
        files = {}
        for name in (
            "backend/app/runtime.py",
            "backend/requirements.lock",
            "web/index.html",
            "deploy/linux/install.sh",
            "deploy/linux/activate.sh",
        ):
            path = self.root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("example release content\n")
            files[name] = hashlib.sha256(path.read_bytes()).hexdigest()
        digest = hashlib.sha256()
        for name, value in sorted(files.items()):
            digest.update(name.encode() + b"\0" + value.encode() + b"\n")
        identifier = digest.hexdigest()[:16]
        (self.root / "release.json").write_text(
            json.dumps({"id": identifier, "files": files})
        )
        return identifier

    def test_modified_or_unlisted_release_files_fail_verification(self):
        identifier = self.prepared()
        self.assertEqual(release.verify(self.root), identifier)
        extra = self.root / "private.env"
        extra.write_text("must not be delivered")
        with self.assertRaises(ValueError):
            release.verify(self.root)
        extra.unlink()
        (self.root / "web/index.html").write_text("modified")
        with self.assertRaises(ValueError):
            release.verify(self.root)

    def test_prepared_venv_does_not_change_the_release_identity(self):
        identifier = self.prepared()
        path = self.root / ".venv/bin/python"
        path.parent.mkdir(parents=True)
        path.write_text("installed separately")
        cache = self.root / "backend/app/__pycache__/runtime.cpython-313.pyc"
        cache.parent.mkdir()
        cache.write_bytes(b"generated bytecode")
        self.assertEqual(release.verify(self.root), identifier)


if __name__ == "__main__":
    unittest.main()
