import { expect, test } from "@playwright/test";

test("local configuration creates and edits real records without corporate login", async ({ page, browser }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const authorization: string[] = [];
  page.on("request", request => {
    if (request.url().includes("/api/") && request.headers()["authorization"]) authorization.push(request.headers()["authorization"]);
  });
  await page.goto("/");
  await expect(page.locator(".local-banner")).toContainText("SQLite");
  await expect(page.getByRole("heading", { name: "Acceso al sistema" })).toHaveCount(0);
  await page.getByRole("navigation", { name: "Secciones" }).getByRole("button", { name: "Masters", exact: true }).click();
  await page.getByLabel("Responsable del master", { exact: true }).selectOption("f0000000-0000-0000-0000-000000000002");
  await page.getByRole("button", { name: "Abrir master", exact: true }).click();
  await page.getByRole("button", { name: "Nuevo embarque" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Empresa *", { exact: true }).fill("MXG");
  await dialog.getByLabel("Tipo de operación *", { exact: true }).selectOption("SI");
  await dialog.getByLabel("Proceso *", { exact: true }).selectOption("RM");
  await dialog.getByLabel("Business unit *", { exact: true }).selectOption("M01");
  await dialog.getByLabel("Departamento *", { exact: true }).selectOption("MAT");
  await dialog.getByLabel("Año de operación *", { exact: true }).fill("2026");
  await dialog.getByRole("button", { name: "Crear embarque", exact: true }).click();
  await expect(dialog.getByRole("heading", { name: "RM1-0001SI26-M01-MAT" })).toBeVisible();
  await dialog.getByLabel("Comentarios").fill("Nota persistente de la API local");
  await dialog.getByRole("button", { name: "Guardar cambios", exact: true }).click();
  await dialog.getByRole("button", { name: "Cerrar detalle", exact: true }).click();
  expect((await page.locator("tbody tr").first().boundingBox())!.y).toBeLessThan(240);
  const origin = page.locator('td[data-row="0"][data-field="origin"]');
  await origin.click();
  await page.keyboard.type("Origen guardado en SQLite");
  await expect(page.getByLabel("Editar Origen", { exact: true })).toHaveValue("Origen guardado en SQLite");
  await page.getByLabel("Editar Origen", { exact: true }).press("Enter");
  await page.locator('td[data-row="0"][data-field="eta"]').click();
  await page.keyboard.type("27/10/2026");
  await page.keyboard.press("Enter");
  await page.getByRole("button", { name: "Guardar cambios", exact: false }).click();
  await expect(page.locator(".save-state")).toHaveText("Sin cambios pendientes");
  // A fresh browser context has no localStorage/sessionStorage from the editing context.
  const context = await browser.newContext();
  const reopened = await context.newPage();
  await reopened.goto("http://127.0.0.1:4200/");
  await expect(reopened.locator(".local-banner")).toBeVisible();
  await reopened.getByRole("navigation", { name: "Secciones" }).getByRole("button", { name: "Masters", exact: true }).click();
  await reopened.getByLabel("Responsable del master", { exact: true }).selectOption("f0000000-0000-0000-0000-000000000002");
  await reopened.getByRole("button", { name: "Abrir master", exact: true }).click();
  await expect(reopened.locator('td[data-row="0"][data-field="origin"]')).toHaveText("Origen guardado en SQLite");
  await expect(reopened.locator('td[data-row="0"][data-field="eta"]')).toHaveText("27/10/2026");
  await reopened.locator(".reference-link").first().click();
  await expect(reopened.getByRole("dialog").getByLabel("Comentarios")).toHaveValue("Nota persistente de la API local");
  await context.close();
  expect(errors).toEqual([]);
  expect(authorization).toEqual([]);
});

test("local responsible masters keep mixed operations separate and save exact provision dates", async ({ page }) => {
  await page.goto("/");
  const navigation = page.getByRole("navigation", { name: "Secciones" });
  await navigation.getByRole("button", { name: "Masters", exact: true }).click();
  const owner = page.getByLabel("Responsable del master", { exact: true });
  await expect(owner.locator("option")).toHaveText(["Selecciona un responsable", "DENI", "MAG", "NAT", "ANDREA", "ALEXA"]);
  await owner.selectOption({ label: "MAG" });
  await page.getByRole("button", { name: "Abrir master", exact: true }).click();
  let reference = "";
  for (const operation of ["AI", "SI"]) {
    await page.getByRole("button", { name: "Nuevo embarque" }).click();
    const dialog = page.getByRole("dialog");
    await dialog.getByLabel("Empresa *", { exact: true }).fill("MXT");
    await dialog.getByLabel("Tipo de operación *", { exact: true }).selectOption(operation);
    await dialog.getByLabel("Business unit *", { exact: true }).selectOption("M46");
    await dialog.getByLabel("Año de operación *", { exact: true }).fill("2026");
    await dialog.getByRole("button", { name: "Crear embarque", exact: true }).click();
    await expect(dialog.getByRole("heading", { name: /RM2-/ })).toBeVisible();
    reference = await dialog.locator("#editor-title").innerText();
    await dialog.getByRole("button", { name: "Cerrar detalle" }).click();
  }
  await expect(page.locator("tbody tr")).toHaveCount(2);
  await expect(page.locator("tbody")).toContainText("Aéreo · Importación");
  await expect(page.locator("tbody")).toContainText("Marítimo · Importación");
  await page.screenshot({ path: "test-results/local/masters-by-owner.png", fullPage: true });
  await navigation.getByRole("button", { name: "Provisiones", exact: true }).click();
  await page.getByLabel("Mes contable").fill("2026-10");
  await page.getByRole("button", { name: "Consultar", exact: true }).click();
  await page.getByRole("button", { name: "Abrir periodo", exact: true }).click();
  await page.getByRole("button", { name: "+ Nueva provisión", exact: true }).click();
  const referenceInput = page.getByRole("combobox", { name: "Referencia del master" });
  await referenceInput.fill(reference);
  const option = page.getByRole("option", { name: new RegExp(reference) });
  await expect(option).toContainText("MAG · M46 · MXT");
  await option.click();
  await page.getByLabel("Proveedor", { exact: true }).selectOption("f0000000-0000-0000-0000-000000000003");
  await page.getByLabel("Concepto", { exact: true }).selectOption("STORAGE");
  await page.getByLabel("Fecha de provisión").fill("2026-10-23");
  await page.getByLabel("Importe neto", { exact: true }).fill("500");
  await page.screenshot({ path: "test-results/local/provision-date.png", fullPage: true });
  await page.getByRole("button", { name: "Guardar borrador", exact: true }).click();
  await expect(page.locator(".finance-table tbody")).toContainText("23/10/2026");
  await expect(page.locator(".finance-table tbody")).toContainText("STORAGE");
});
